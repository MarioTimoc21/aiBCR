# Conectare la baza de date
conn = sqlite3.connect(db_path)

# Verifică dacă tabelul există
cursor = conn.cursor()
cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='hackathon_data'")
if not cursor.fetchone():
    print("❌ Tabelul 'hackathon_data' nu există în baza de date.")
    conn.close()
    exit()

# Încarcă datele într-un DataFrame
df = pd.read_sql_query("SELECT * FROM hackathon_data", conn)

# Aplică redenumirea
df.rename(columns=column_mapping, inplace=True)

df.to_sql("hackathon_data_renamed", conn, if_exists="replace", index=False)

print(f"✔ Coloanele au fost redenumite")

